import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RESERVED = new Set([
	"break",
	"case",
	"catch",
	"class",
	"const",
	"continue",
	"debugger",
	"default",
	"delete",
	"do",
	"else",
	"enum",
	"export",
	"extends",
	"false",
	"finally",
	"for",
	"function",
	"if",
	"implements",
	"import",
	"in",
	"instanceof",
	"interface",
	"let",
	"new",
	"null",
	"package",
	"private",
	"protected",
	"public",
	"return",
	"static",
	"super",
	"switch",
	"this",
	"throw",
	"true",
	"try",
	"typeof",
	"var",
	"void",
	"while",
	"with",
	"yield",
	"await",
]);

/** `modal-open` -> `modalOpen`, `delete` -> `deleteSound`. */
export function toIdentifier(name: string): string {
	let id = name
		.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c: string | undefined) =>
			c ? c.toUpperCase() : "",
		)
		.replace(/^[A-Z]/, (c) => c.toLowerCase());
	if (/^[0-9]/.test(id)) id = `sound${id}`;
	if (!id) id = "sound";
	if (RESERVED.has(id)) id = `${id}Sound`;
	return id;
}

/** `Modal Open!` -> `modal-open`. */
export function toFileName(name: string): string {
	return name
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-|-$/g, "");
}

export type SoundModule = {
	sound: string;
	theme: string;
	definition: unknown;
	custom?: boolean;
};

export function renderSoundModule(mod: SoundModule): string {
	const meta = JSON.stringify({
		theme: mod.theme,
		sound: mod.sound,
		...(mod.custom ? { custom: true } : {}),
	});
	const id = toIdentifier(mod.sound);
	const body = JSON.stringify(mod.definition, null, "\t");
	return [
		`// @audx ${meta}`,
		mod.custom
			? "// Customized on audx.site. `audx theme` and `audx update` leave this file alone."
			: "// Generated by audx. Swap the whole set with `npx @litlab/audx theme <name>`.",
		`import { defineSound } from "@litlab/audx";`,
		"",
		`export const ${id} = defineSound(${body});`,
		"",
	].join("\n");
}

export function renderIndex(files: string[]): string {
	const lines = [
		"// Generated by audx. Updated automatically by `audx add` and `audx remove`.",
		...files
			.slice()
			.sort()
			.map((f) => `export { ${toIdentifier(f)} } from "./${f}";`),
		"",
	];
	return lines.join("\n");
}

export function writeSoundFile(
	dir: string,
	ext: "ts" | "js",
	mod: SoundModule,
) {
	if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
	const file = toFileName(mod.sound);
	writeFileSync(join(dir, `${file}.${ext}`), renderSoundModule(mod), "utf-8");
	return file;
}

/** Rebuilds `index.ts|js` from whatever sound files are in `dir`. */
export function writeIndex(dir: string, ext: "ts" | "js") {
	if (!existsSync(dir)) return;
	const files = readdirSync(dir)
		.map((f) => f.match(/^(.+)\.(ts|js)$/)?.[1])
		.filter((f): f is string => !!f && f !== "index");
	writeFileSync(join(dir, `index.${ext}`), renderIndex(files), "utf-8");
}

export function soundFileExists(dir: string, sound: string): string | null {
	const file = toFileName(sound);
	for (const ext of ["ts", "js"]) {
		if (existsSync(join(dir, `${file}.${ext}`))) return `${file}.${ext}`;
	}
	return null;
}
